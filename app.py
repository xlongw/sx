def fetch_stock_data_baostock(code, start_date, end_date):
    """Fetch daily data for a single stock via Baostock (free, no registration needed)."""
    c = str(code)
    if c.startswith("6"):
        bs_code = f"sh.{c}"
    else:
        bs_code = f"sz.{c}"

    try:
        rs = bs.query_history_k_data_plus(
            bs_code,
            "date,open,high,low,close,volume",
            start_date=start_date,
            end_date=end_date,
            frequency="d",
            adjustflag="2",  # 前复权
        )

        if rs is None or rs.error_code != "0":
            logger.warning(f"baostock query failed for {code}: {rs.error_msg if rs else 'rs is None'}")
            return None

        data_list = []
        while rs.next():
            data_list.append(rs.get_row_data())

        if not data_list:
            return None

        df = pd.DataFrame(data_list, columns=["date", "open", "high", "low", "close", "volume"])
        df["date"] = pd.to_datetime(df["date"])
        for col in ["open", "high", "low", "close", "volume"]:
            df[col] = pd.to_numeric(df[col], errors="coerce")

        return df[["date", "open", "high", "low", "close", "volume"]]
    except Exception as e:
        logger.error(f"baostock fetch failed for {code}: {e}")
        return None


def fetch_stock_data(code, days=250, force_refresh=False):
    """
    Fetch stock data with caching strategy.
    Returns DataFrame or None.
    """
    end_date = datetime.now().strftime("%Y-%m-%d")
    start_date = (datetime.now() - timedelta(days=days + 30)).strftime("%Y-%m-%d")

    # Check cache first
    if not force_refresh:
        cached = load_from_db(code, limit=days)
        if len(cached) >= 120:
            latest_cached = cached["date"].max()
            if latest_cached and (datetime.now() - latest_cached).days < 1:
                return cached.tail(days)

    # Fetch from Baostock API
    df = fetch_stock_data_baostock(code, start_date, end_date)

    return df


def fetch_and_cache_stock(code, name, days=250, progress_callback=None):
    """
    Fetch stock data and save to cache. Returns DataFrame or None.
    """
    try:
        df = fetch_stock_data(code, days=days, force_refresh=False)
        if df is not None and len(df) >= 60:
            save_to_db(df, code, name)
            return df
        elif df is not None:
            msg = f"数据不足 (仅{len(df)}天): {code} {name}"
            logger.warning(msg)
            with open("log.txt", "a", encoding="utf-8") as f:
                f.write(f"{datetime.now()} - {msg}\n")
            # Still save what we have
            save_to_db(df, code, name)
            return None
        else:
            return None
    except Exception as e:
        msg = f"获取失败 {code} {name}: {e}"
        logger.error(msg)
        return None


# ── 技术指标计算 ──────────────────────────────────────────
def calc_indicators(df):
    """Calculate EMA21, EMA55, EMA120, ATR5, and related metrics. (Vectorized)"""
    df = df.copy()
    df["ema21"] = df["close"].ewm(span=21, adjust=False).mean()
    df["ema55"] = df["close"].ewm(span=55, adjust=False).mean()
    df["ema120"] = df["close"].ewm(span=120, adjust=False).mean()

    # ATR(5)
    prev_close = df["close"].shift(1)
    tr1 = df["high"] - df["low"]
    tr2 = (df["high"] - prev_close).abs()
    tr3 = (df["low"] - prev_close).abs()
    df["tr"] = np.maximum(tr1, np.maximum(tr2, tr3))
    df["atr5"] = df["tr"].rolling(5).mean()

    # 5-day high/low ratio
    df["high5"] = df["high"].rolling(5).max()
    df["low5"] = df["low"].rolling(5).min()

    return df


def check_condition_a(df):
    """
    Condition A: First day close > ALL three EMAs (21, 55, 120).
    Yesterday did NOT satisfy this condition.
    """
    above_all = (
        (df["close"] > df["ema21"]) &
        (df["close"] > df["ema55"]) &
        (df["close"] > df["ema120"])
    )
    # Today is the first day above all three
    condition = above_all & ~above_all.shift(1).fillna(False)
    return condition


def check_condition_b(df, threshold=1.02):
    """
    Condition B: Three EMAs converge.
    max(EMA21, EMA55, EMA120) / min(EMA21, EMA55, EMA120) <= threshold.
    AND close price deviation from EMA mean <= 3%.
    """
    ema_cols = df[["ema21", "ema55", "ema120"]]
    ema_max = ema_cols.max(axis=1)
    ema_min = ema_cols.min(axis=1)
    ema_ratio = ema_max / ema_min
    ema_mean = ema_cols.mean(axis=1)
    close_dev = (df["close"] - ema_mean).abs() / ema_mean

    condition = (ema_ratio <= threshold) & (close_dev <= 0.03)
    return condition


def check_condition_c(df, threshold=0.02):
    """
    Condition C: Low volatility near EMAs.
    Close price within <threshold> of each EMA, AND
    ATR(5)/close < 3% OR recent 5-day high/low ratio < 1.05.
    """
    dev_21 = (df["close"] - df["ema21"]).abs() / df["ema21"]
    dev_55 = (df["close"] - df["ema55"]).abs() / df["ema55"]
    dev_120 = (df["close"] - df["ema120"]).abs() / df["ema120"]
    near_emas = (dev_21 < threshold) & (dev_55 < threshold) & (dev_120 < threshold)

    low_vol_atr = df["atr5"] / df["close"] < 0.03
    low_vol_range = df["high5"] / df["low5"] < 1.05
    low_vol = low_vol_atr | low_vol_range

    condition = near_emas & low_vol
    return condition


# ── 筛选主函数 ────────────────────────────────────────────
def screen_single_stock(df, code, name, logic_mode, threshold_b, threshold_c,
                        enabled_a, enabled_b, enabled_c):
    """
    Screen a single stock. Returns list of signal dicts.
    """
    if df is None or len(df) < 120:
        return []

    df = calc_indicators(df)
    latest = df.iloc[-1]  # Only check the most recent trading day

    cond_a = check_condition_a(df).iloc[-1] if enabled_a else False
    cond_b = check_condition_b(df, threshold_b).iloc[-1] if enabled_b else False
    cond_c = check_condition_c(df, threshold_c).iloc[-1] if enabled_c else False

    # Apply logic
    if logic_mode == "AND":
        active_conditions = []
        if enabled_a: active_conditions.append(cond_a)
        if enabled_b: active_conditions.append(cond_b)
        if enabled_c: active_conditions.append(cond_c)
        if not active_conditions:
            triggered = False
        else:
            triggered = all(active_conditions)
    else:  # OR
        triggered = cond_a or cond_b or cond_c

    if not triggered:
        return []

    # Build signal info
    ema_mean_val = float(latest[["ema21","ema55","ema120"]].mean())
    deviation = float(abs(latest["close"] - ema_mean_val) / ema_mean_val * 100)

    signal_types = []
    if enabled_a and cond_a:
        signal_types.append("A-首次站上三线")
    if enabled_b and cond_b:
        signal_types.append("B-均线粘合")
    if enabled_c and cond_c:
        signal_types.append("C-低波动")

    return [{
        "code": code,
        "name": name,
        "date": str(latest["date"])[:10],
        "close": round(float(latest["close"]), 2),
        "ema21": round(float(latest["ema21"]), 2),
        "ema55": round(float(latest["ema55"]), 2),
        "ema120": round(float(latest["ema120"]), 2),
        "deviation_pct": round(deviation, 2),
        "signal": " + ".join(signal_types),
        "cond_a": cond_a,
        "cond_b": cond_b,
        "cond_c": cond_c,
    }]


# ── K线图 ─────────────────────────────────────────────────
def plot_kline_with_emas(df, code, name, signal_date, signal_types, days=60):
    """
    绘制交互式K线图（含EMA均线、成交量、信号标记）。
    红涨绿跌（国内习惯）。

    Test case built-in: 000001 (平安银行) recent 60-day chart
    - 蜡烛图：红涨绿跌
    - 三条EMA线：蓝色EMA21、橙色EMA55、紫色EMA120
    - 成交量柱状图与日期对齐
    - 若空头排列：EMA21 < EMA55 < EMA120
    """
    from plotly.subplots import make_subplots
    import plotly.graph_objects as go

    df = df.tail(days).copy()
    df = calc_indicators(df)

    fig = make_subplots(
        rows=2, cols=1, shared_xaxes=True,
        row_heights=[0.7, 0.3], vertical_spacing=0.03,
        subplot_titles=(f"{code} {name}", "成交量"),
    )

    # ── 蜡烛图（红涨绿跌） ──
    fig.add_trace(
        go.Candlestick(
            x=df["date"], open=df["open"], high=df["high"],
            low=df["low"], close=df["close"], name="K线",
            increasing=dict(line=dict(color="red"), fillcolor="red"),
            decreasing=dict(line=dict(color="green"), fillcolor="green"),
            hovertext=[
                f"日期: {d.strftime('%Y-%m-%d')}<br>"
                f"开: {o:.2f}<br>高: {h:.2f}<br>低: {l:.2f}<br>收: {c:.2f}"
                for d, o, h, l, c in zip(df["date"], df["open"], df["high"],
                                         df["low"], df["close"])
            ],
            hoverinfo="text",
        ),
        row=1, col=1,
    )

    # ── 三条EMA均线 ──
    fig.add_trace(
        go.Scatter(x=df["date"], y=df["ema21"],
                   line=dict(color="blue", width=1.2), name="EMA21",
                   hovertemplate="EMA21: %{y:.2f}<extra></extra>"),
        row=1, col=1,
    )
    fig.add_trace(
        go.Scatter(x=df["date"], y=df["ema55"],
                   line=dict(color="orange", width=1.2), name="EMA55",
                   hovertemplate="EMA55: %{y:.2f}<extra></extra>"),
        row=1, col=1,
    )
    fig.add_trace(
        go.Scatter(x=df["date"], y=df["ema120"],
                   line=dict(color="purple", width=1.2), name="EMA120",
                   hovertemplate="EMA120: %{y:.2f}<extra></extra>"),
        row=1, col=1,
    )

    # ── 信号标记 ──
    marker_symbols = {
        "A": ("triangle-up", "limegreen", 14, "⬆ 首次站上三线"),
        "B": ("circle", "gold", 12, "🟡 均线粘合"),
        "C": ("square", "dodgerblue", 12, "🟦 低波动"),
    }
    for stype in signal_types:
        key = stype[0]  # First char: A, B, or C
        if key in marker_symbols:
            sym, color, size, label = marker_symbols[key]
            try:
                sig_date = pd.to_datetime(signal_date)
                mask = df["date"] == sig_date
                if mask.any():
                    y_val = float(df.loc[mask, "high"].values[0]) * 1.02
                    x_val = df.loc[mask, "date"].values[0]
                    fig.add_trace(
                        go.Scatter(
                            x=[x_val], y=[y_val], mode="markers",
                            marker=dict(symbol=sym, color=color, size=size, line=dict(width=1, color="black")),
                            name=label, showlegend=True,
                            hovertemplate=f"{label}<br>%{{x|%Y-%m-%d}}<extra></extra>",
                        ),
                        row=1, col=1,
                    )
            except Exception as e:
                logger.warning(f"Failed to add marker for {stype}: {e}")

    # ── 成交量 ──
    vol_colors = [
        "red" if df["close"].iloc[i] >= df["open"].iloc[i] else "green"
        for i in range(len(df))
    ]
    fig.add_trace(
        go.Bar(x=df["date"], y=df["volume"], name="成交量",
               marker_color=vol_colors,
               hovertemplate="成交量: %{y:,.0f}<extra></extra>"),
        row=2, col=1,
    )

    # ── 布局 ──
    current_price = float(df["close"].iloc[-1])
    signal_str = " + ".join(signal_types) if signal_types else "无信号"
    fig.update_layout(
        title=dict(
            text=f"<b>{code} {name}</b> | 当前价: {current_price:.2f} | 触发条件: {signal_str}",
            font=dict(size=16),
        ),
        height=650,
        xaxis_rangeslider_visible=False,
        xaxis2_rangeslider_visible=False,
        hovermode="closest",
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
        margin=dict(l=10, r=10, t=60, b=10),
        template="plotly_white",
    )
    fig.update_xaxes(title_text="日期", row=2, col=1)
    fig.update_yaxes(title_text="价格", row=1, col=1)
    fig.update_yaxes(title_text="成交量", row=2, col=1)

    return fig


