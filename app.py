def init_db():
    """Initialize SQLite database and create table if not exists."""
    with sqlite3.connect(DB_PATH) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS daily_quotes (
                code TEXT,
                date TEXT,
                open REAL,
                high REAL,
                low REAL,
                close REAL,
                volume REAL,
                name TEXT,
                PRIMARY KEY (code, date)
            )
        """)
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_code ON daily_quotes(code)
        """)
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_date ON daily_quotes(date)
        """)


def save_to_db(df, code, name):
    """Save a single stock's data to SQLite (upsert)."""
    if df is None or df.empty:
        return
    df = df.copy()
    df["code"] = code
    df["name"] = name
    with sqlite3.connect(DB_PATH) as conn:
        for _, row in df.iterrows():
            conn.execute(
                """INSERT OR REPLACE INTO daily_quotes (code, date, open, high, low, close, volume, name)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (code, str(row["date"])[:10], float(row["open"]),
                 float(row["high"]), float(row["low"]), float(row["close"]),
                 float(row["volume"]), str(name)),
            )


def load_from_db(code, limit=250):
    """Load stock data from SQLite cache."""
    with sqlite3.connect(DB_PATH) as conn:
        df = pd.read_sql_query(
            "SELECT date, open, high, low, close, volume, name FROM daily_quotes "
            "WHERE code = ? ORDER BY date DESC LIMIT ?",
            conn, params=(code, limit),
        )
    if df.empty:
        return df
    df["date"] = pd.to_datetime(df["date"])
    return df.sort_values("date").reset_index(drop=True)


def get_cached_date(code):
    """Return the latest cached date for a stock, or None."""
    with sqlite3.connect(DB_PATH) as conn:
        row = conn.execute(
            "SELECT MAX(date) FROM daily_quotes WHERE code = ?", (code,)
        ).fetchone()
    return row[0] if row and row[0] else None


def get_all_cached_codes():
    """Return set of all stock codes in cache."""
    with sqlite3.connect(DB_PATH) as conn:
        rows = conn.execute("SELECT DISTINCT code FROM daily_quotes").fetchall()
    return {r[0] for r in rows}


